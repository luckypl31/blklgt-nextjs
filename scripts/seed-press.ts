// seed/insert script. Every entry below was found via web search and
// verified against the actual source before being included; nothing here
// is a fabricated quote.
//
// A few honesty calls, worth knowing before you publish these:
//   - Black Heat's actual critical reception is mixed-to-negative. Variety's
//     review is lukewarm ("energetic if basic"), and a couple of other
//     outlets were rougher than that. Rather than cherry-pick an
//     out-of-context positive-sounding fragment from a mixed review, Variety
//     is listed as an outlet placement with NO pull-quote — being reviewed
//     by Variety at all is a legitimate trade-press signal on its own.
//   - Deadline and EURweb entries are straight announcement pieces, not
//     reviews, so there was nothing evaluative to quote — outlet + link only.
//   - Every quote that IS included is a genuine, verbatim, under-15-word
//     line from the actual critic or the actual person quoted (Miller,
//     NLE Choppa), not a paraphrase dressed up as a quotation.
//   - The Essence Film Festival win is not duplicated here — it's already
//     on the Wildcards film record's `awards` array and shows on /press via
//     the Trophy Case, which pulls from that field directly. Adding it again
//     here would just be the same recognition shown twice.
//   - The "Sarah G. Vincent Views" entry is correctly named — verified
//     against the actual byline before adding.
//   - Two pieces sent for this batch were deliberately left OUT:
//       - MixTV1's Wildcards trailer post carries the site's own disclosure
//         that the article is "partially generated by artificial
//         intelligence." That's not an editorial press placement — it's
//         syndicated/rewritten content, and it would undercut this page's
//         credibility with anyone who clicked through and saw that notice.
//       - The PIX11 "Leon & The Peoples" URL didn't match what was
//         described — the page found at that address covers a reggae-soul
//         band by a similar name, not actor Leon Robinson or Wildcards. Left
//         out rather than guessed at; worth double-checking the link.
//
// Safe to re-run — merge:true, so it won't clobber anything you've since
// edited in the admin console. Doc ids are stable slugs, not random ids, so
// running this twice updates instead of duplicating.
//
//   npm run seed:press
//
// Needs serviceAccount.json (see scripts/migrate-admin.ts for how to get one).
// ---------------------------------------------------------------------------

