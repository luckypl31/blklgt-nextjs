async function main() {
  let serviceAccount: Record<string, string>;
  try {
    serviceAccount = JSON.parse(readFileSync(KEY_PATH, 'utf8'));
  } catch {
    console.error(`\nNo service account key at ${KEY_PATH}.\nSee scripts/migrate-admin.ts for how to generate one.\n`);
    process.exit(1);
  }

  initializeApp({ credential: cert(serviceAccount as never) });
  const db = getFirestore();
  const batch = db.batch();

  PRESS.forEach(({ id, ...rest }) => {
    batch.set(db.collection('press').doc(id), rest, { merge: true });
  });

  await batch.commit();
  console.log(`\nSeeded ${PRESS.length} press mentions.`);
  console.log('Edit or remove any of these anytime in /admin/press.\n');
  process.exit(0);
}

main().catch((e) => {
  console.error('\nSeed failed:', e?.message ?? e);
  process.exit(1);
});
